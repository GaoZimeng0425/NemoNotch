import Foundation

/// Picks what the user actually typed out of a transcript's user-role lines.
/// Claude Code also records injected text as user lines and those made toast
/// titles unreadable. Its own `isMeta` flag marks most of them (skill bodies,
/// command expansions, caveats, image placeholders); the prefixes below catch
/// the injected shapes that carry no flag.
enum UserPrompt {
    private static let injectedPrefixes = [
        "<", // <task-notification>, <command-name>, <local-command-stdout>, <system-reminder>…
        "This session is being continued from a previous conversation",
        "[Image:", // "[Image #1] …" is a real prompt with a pasted image
        "[Request interrupted",
        "Caveat: The messages below were generated by the user while running local commands",
    ]

    static func isTyped(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        return !trimmed.isEmpty && !injectedPrefixes.contains { trimmed.hasPrefix($0) }
    }

    /// The first typed prompt among `messages`, cut to 80 characters.
    static func first(in messages: [ChatMessage]) -> String? {
        messages.first { $0.role == .user && !$0.isMeta && isTyped($0.content) }.map { String($0.content.prefix(80)) }
    }

    /// The last typed prompt among `messages`, cut to 80 characters.
    static func last(in messages: [ChatMessage]) -> String? {
        messages.last { $0.role == .user && !$0.isMeta && isTyped($0.content) }.map { String($0.content.prefix(80)) }
    }
}
