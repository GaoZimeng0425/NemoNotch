import Foundation

/// Installs/removes the opencode plugin that forwards session lifecycle events
/// to NemoNotch's HookServer. opencode auto-loads `*.ts` from its global
/// `~/.config/opencode/plugin/` directory, so dropping the file IS the
/// registration — no `opencode.json` edit needed. Mirrors HermesHookInstaller.
enum OpencodePluginInstaller {
    private static let pluginDir = NSHomeDirectory() + "/.config/opencode/plugin"
    private static let pluginPath = pluginDir + "/nemonotch-notify.ts"
    static let marker = "nemonotch-opencode-plugin"
    static let version = "v3"

    static var isInstalled: Bool {
        guard let content = try? String(contentsOfFile: pluginPath, encoding: .utf8) else { return false }
        return content.contains(marker)
    }

    static func install() throws {
        try writePlugin()
    }

    static func uninstall() throws {
        guard FileManager.default.fileExists(atPath: pluginPath) else { return }
        try FileManager.default.removeItem(atPath: pluginPath)
        LogService.info("opencode plugin uninstalled", category: "OpencodePluginInstaller")
    }

    /// Rewrite the plugin with the current hook-server port. Called on launch /
    /// port change (HookServer) when already installed. No-op otherwise.
    static func refreshScript() throws {
        guard isInstalled else { return }
        try writePlugin()
    }

    private static func writePlugin() throws {
        try FileManager.default.createDirectory(atPath: pluginDir, withIntermediateDirectories: true)
        let port = NotchConstants.hookServerPort
        try pluginSource(port: port).write(toFile: pluginPath, atomically: true, encoding: .utf8)
        LogService.info("Wrote opencode plugin (port \(port))", category: "OpencodePluginInstaller")
    }

    /// Pure generator — the plugin's TS source for a given port. Kept internal
    /// (not private) so it can be unit-tested without touching the filesystem.
    static func pluginSource(port: UInt16) -> String {
        """
        import { readFileSync } from "node:fs"
        import { homedir } from "node:os"

        // \(marker) \(version) — auto-generated by NemoNotch. Do not edit by hand.
        // Forwards opencode session lifecycle to NemoNotch and applies bar-side
        // permission answers through opencode's own client API.
        const URL_BASE = "http://127.0.0.1:\(port)"

        // Shared auth token: the server rejects /hook POSTs without it.
        let hookToken = ""
        try { hookToken = readFileSync(homedir() + "/.NemoNotch/hook-token", "utf8").trim() } catch (_) {}

        const HEADERS = { "Content-Type": "application/json", "X-NemoNotch-Token": hookToken }

        const post = (body) => {
          try {
            fetch(URL_BASE + "/hook", {
              method: "POST",
              headers: HEADERS,
              body: JSON.stringify(body),
              signal: AbortSignal.timeout(1500),
            }).catch(() => {})
          } catch (_) {}
        }

        export const NemoNotchNotify = async (input) => {
          const directory = input && input.directory
          const client = input && input.client
          const base = (extra) => ({ cwd: directory, cli_source: "opencode", ...extra })
          // sessionID → AbortController of the held bridge (newest wins)
          const pending = new Map()

          // Apply a bar-side decision through opencode's own client API. Only
          // "once"/"reject" are ever sent; the persistent-allow option is
          // deliberately never sent (it would write a rule into the user's
          // opencode). Silently skipped when the plugin input carries
          // no client (unknown version); opencode's TUI stays the decider.
          const reply = (sessionID, permissionId, decision) => {
            if (!client || typeof client.postSessionIdPermissionsPermissionId !== "function") return
            try {
              Promise.resolve(
                client.postSessionIdPermissionsPermissionId({
                  path: { id: sessionID, permissionID: permissionId },
                  body: { response: decision },
                }),
              ).catch(() => {})
            } catch (_) {}
          }

          const applyDecision = (sessionID, permissionId, body) => {
            const output = body && body.hookSpecificOutput
            const decision = output && output.decision
            const behavior = decision && decision.behavior
            if (behavior === "allow") reply(sessionID, permissionId, "once")
            else if (behavior === "deny" && decision.message !== "timeout") reply(sessionID, permissionId, "reject")
            // deny(timeout) / no decision → opencode's own dialog remains in charge
          }

          // The bridge: a second POST held open by NemoNotch while opencode's
          // own TUI dialog stays up. NOT awaited — the ask handler returns at
          // once, and whichever of [TUI, bar] answers first wins (the loser is
          // aborted via permission.replied / session.idle).
          const holdBridge = (perm) => {
            const controller = new AbortController()
            const previous = pending.get(perm.sessionID)
            if (previous) previous.abort()
            pending.set(perm.sessionID, controller)
            try {
              fetch(URL_BASE + "/hook", {
                method: "POST",
                headers: HEADERS,
                body: JSON.stringify(base({
                  hook_event_name: "PermissionRequest",
                  session_id: perm.sessionID,
                  tool_name: perm.type || perm.title,
                  tool_use_id: perm.id,
                  message: perm.title || perm.pattern,
                })),
                signal: controller.signal,
              })
                .then((resp) => (resp && resp.json ? resp.json().catch(() => ({})) : {}))
                .then((body) => {
                  if (pending.get(perm.sessionID) === controller) pending.delete(perm.sessionID)
                  applyDecision(perm.sessionID, perm.id, body)
                })
                .catch(() => {
                  if (pending.get(perm.sessionID) === controller) pending.delete(perm.sessionID)
                })
            } catch (_) {}
          }

          const abortBridge = (sessionID) => {
            const controller = pending.get(sessionID)
            if (controller) {
              controller.abort()
              pending.delete(sessionID)
            }
          }

          return {
            "chat.message": async (input) => {
              const model = input && input.model ? input.model.providerID + "/" + input.model.modelID : undefined
              post(base({ hook_event_name: "UserPromptSubmit", session_id: input.sessionID, model }))
            },
            "tool.execute.before": async (input) => {
              post(base({ hook_event_name: "PreToolUse", session_id: input.sessionID, tool_name: input.tool, tool_use_id: input.callID }))
            },
            "tool.execute.after": async (input) => {
              post(base({ hook_event_name: "PostToolUse", session_id: input.sessionID, tool_name: input.tool, tool_use_id: input.callID }))
            },
            "permission.ask": async (perm) => {
              if (!perm || !perm.sessionID) return
              holdBridge(perm)
            },
            event: async ({ event }) => {
              const sid = event && event.properties ? event.properties.sessionID : undefined
              if (!sid) return
              if (event.type === "session.idle" || event.type === "session.error") {
                abortBridge(sid)
                post(base({ hook_event_name: "Stop", session_id: sid }))
              } else if (event.type === "session.compacted") {
                post(base({ hook_event_name: "PreCompact", session_id: sid }))
              } else if (event.type === "permission.replied") {
                // The TUI (or our applied answer) decided — lift the notch's
                // waiting card and drop our held copy.
                abortBridge(sid)
                post(base({ hook_event_name: "PostToolUse", session_id: sid }))
              }
            },
          }
        }
        """
    }
}
